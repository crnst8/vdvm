// Reference renders of the browser tape echo (src/audio/echo/dsp.ts). The C++
// core tests run the same cases through plugin/source/core/TapeEcho.cpp and
// compare against plugin/source/tests/data/echo-reference.json; tests/echo.test.ts
// fails when the file no longer matches the TypeScript DSP.
//   npx tsx plugin/scripts/echo-reference.ts [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { TapeEcho, type EchoDspParams } from '../../src/audio/echo/dsp.ts'

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../source/tests/data/echo-reference.json')

const BLOCK = 128
const STRIDE = 97

interface Case {
  name: string
  sampleRate: number
  frames: number
  /** Parameter changes at block-aligned frames; the first is at 0. */
  changes: { at: number; params: EchoDspParams }[]
}

const base: EchoDspParams = {
  on: true, heads: [true, false, true], spring: true, speed: 0.8, intensity: 0.5, echo: 0.6, reverb: 0.5,
  bass: 0.6, treble: 0.4, input: 0.6, tape: 'used',
}
const at = (sec: number, fs: number) => Math.round((sec * fs) / BLOCK) * BLOCK

export const cases: Case[] = [
  { name: 'heads 1+3, spring, motor slowing', sampleRate: 48000, frames: at(1.5, 48000), changes: [
    { at: 0, params: base },
    { at: at(0.7, 48000), params: { ...base, speed: 0.45 } },
  ] },
  { name: 'three heads, old tape, high intensity, then off', sampleRate: 44100, frames: at(1.2, 44100), changes: [
    { at: 0, params: { ...base, heads: [true, true, true], spring: false, speed: 1, intensity: 0.75, bass: 0.7, treble: 0.5, tape: 'old' } },
    { at: at(0.9, 44100), params: { ...base, on: false, heads: [true, true, true], spring: false, speed: 1, intensity: 0.75, bass: 0.7, treble: 0.5, tape: 'old' } },
  ] },
]

/** Test input: decaying 220 Hz bursts every 0.37 s and a click every 0.53 s; computed the same way in C++. */
export function input(i: number, fs: number) {
  const burst = Math.round(0.37 * fs), click = Math.round(0.53 * fs)
  const v = 0.4 * Math.sin((2 * Math.PI * 220 * i) / fs) * Math.exp(-(i % burst) / (0.05 * fs)) + (i % click === 0 ? 0.6 : 0)
  return Math.fround(v)
}

export function renderCase(c: Case): number[] {
  const echo = new TapeEcho(c.sampleRate)
  const x = new Float32Array(c.frames).map((_, i) => input(i, c.sampleRate))
  const left = new Float32Array(c.frames), right = new Float32Array(c.frames)
  let next = 0
  for (let o = 0; o < c.frames; o += BLOCK) {
    while (next < c.changes.length && c.changes[next].at <= o) echo.set(c.changes[next++].params)
    const n = Math.min(BLOCK, c.frames - o)
    echo.process(x.subarray(o, o + n), left.subarray(o, o + n), right.subarray(o, o + n), n)
  }
  const samples: number[] = []
  for (let i = 0; i < c.frames; i += STRIDE) samples.push(left[i])
  return samples
}

export function reference() {
  return {
    note: 'Generated by plugin/scripts/echo-reference.ts from src/audio/echo/dsp.ts. Do not edit.',
    block: BLOCK,
    stride: STRIDE,
    cases: cases.map((c) => ({ ...c, left: renderCase(c) })),
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = JSON.stringify(reference()) + '\n'
  if (process.argv.includes('--check')) {
    if (readFileSync(out, 'utf8') !== text) {
      console.error(`${out} is stale. Run: npx tsx plugin/scripts/echo-reference.ts`)
      process.exit(1)
    }
    console.log('echo-reference.json is current')
  } else {
    writeFileSync(out, text)
    console.log(`wrote ${out}`)
  }
}
